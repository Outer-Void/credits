#!/usr/bin/env python3
"""Render ACKNOWLEDGMENTS.md, the human-readable view of the credits data.

Usage: tools/render_acknowledgments.py [--check]
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent

ROLE_WORDS = {
    "creator": "created", "co_creator": "co-created", "founder": "founded", "co_founder": "co-founded",
    "original_author": "originally wrote", "author": "authored", "editor": "edited", "developer": "developed",
    "maintainer": "maintains", "contributor": "contributed to", "copyright_holder": "holds copyright in",
    "steward": "stewards", "host": "hosts", "community": "is the community behind",
    "upstream_source": "is an upstream source of", "fork_origin": "is the fork origin of",
    "nested_upstream": "is nested upstream work in", "legal_attribution": "requires attribution in",
    "inspiration": "inspired", "architectural_influence": "influenced the architecture of",
    "ai_assistance": "assisted development of", "model": "is a model used by",
    "historical_lineage": "is historical lineage of",
}  # fmt: skip
GROUPS = [
    ("Upstream sources and lineage", lambda i, r: "UPSTREAM_SOURCE" in rels(r) or "FORK_OR_DERIVATIVE" in rels(r)
     or i.startswith("proj:")),
    ("AI and machine assistance", lambda i, r: i.startswith("ai:")),
    ("Models and runtimes", lambda i, r: i.startswith("model:")),
    ("Languages, platforms and tooling", lambda i, r: i.startswith("tool:")),
    ("Libraries and frameworks", lambda i, r: i.startswith("lib:")),
    ("Standards and specifications", lambda i, r: i.startswith("std:")),
    ("Datasets", lambda i, r: i.startswith("ds:")),
    ("Fonts, images and other assets", lambda i, r: i.startswith("asset:")),
    ("Inspirations (voluntary credit; no code derivation implied)", lambda i, r: i.startswith("insp:")),
]


def rels(rec: dict[str, Any]) -> list[str]:
    return list(rec.get("relationship") or [])


def load_all(root: Path) -> tuple[dict[str, dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    records: dict[str, dict[str, Any]] = {}
    for path in sorted((root / "catalog").glob("*.yaml")) + sorted((root / "provenance").glob("*.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for key, items in doc.items():
            if key == "schema_version":
                continue
            for rec in items or []:
                if isinstance(rec, dict) and "id" in rec:
                    records[rec["id"]] = rec
    for path in sorted((root / "projects").glob("*.yaml")):
        rec = yaml.safe_load(path.read_text(encoding="utf-8"))["project"]
        records[rec["id"]] = rec
    repo_map = yaml.safe_load((root / "provenance" / "repository-map.yaml").read_text(encoding="utf-8"))["repositories"]
    graph = root / "provenance" / "attribution-graph.yaml"
    edges = (yaml.safe_load(graph.read_text(encoding="utf-8")) or {}).get("edges", []) if graph.is_file() else []
    return records, repo_map, edges


def name(records: dict[str, dict[str, Any]], rid: str) -> str:
    rec = records.get(rid, {})
    return str(rec.get("name") or (rec.get("products") or [rid])[0])


def source_link(src: dict[str, Any]) -> str:
    ref = str(src.get("ref"))
    if ref.startswith("https://"):
        return f"[{src.get('kind')}]({ref})"
    if ref.startswith("credits:"):
        return f"[{src.get('kind')}]({ref[len('credits:'):]})"
    return f"{src.get('kind')} ({ref})"


def render(root: Path = ROOT) -> str:
    records, repo_map, edges = load_all(root)
    affects: dict[str, list[str]] = defaultdict(list)
    for rid, rec in records.items():
        vals = rec.get("affects")
        for target in [vals] if isinstance(vals, str) else (vals or []):
            affects[str(target)].append(rid)
    out = [
        "# Acknowledgments",
        "",
        "<!-- GENERATED by tools/render_acknowledgments.py from catalog/, projects/ and provenance/. Edit the data. -->",
        "",
        "> **We acknowledge the shoulders we stand on.** Outer Void is built on generations of prior work. This",
        "> page thanks the people, communities, projects, technologies, standards, tools, models and ideas that",
        "> enabled or influenced it, and says what each actually was ([GOVERNANCE.md](GOVERNANCE.md)).",
        "",
        "Acknowledgment here is voluntary and implies no endorsement, sponsorship, affiliation or authorship of",
        "Outer Void work. It is separate from legal attribution. The notices that licences require travel with each",
        "repository (`LICENSE`, `NOTICE`, `THIRD_PARTY_NOTICES.md`, `licenses/`), and are indexed under",
        "[Legal notices](#legal-notices-indexed-separately) below. A credit never replaces one.",
        "",
        "Every entry carries its evidence in the data files. Unconfirmed attribution is not shown as fact; it is",
        "listed in [reports/unresolved-provenance.md](reports/unresolved-provenance.md).",
        "",
        "## Contents",
        "",
        "- [Who and what we credit, work by work](#who-and-what-we-credit-work-by-work)",
        "- [People](#people)",
        "- [Communities and organizations](#communities-and-organizations)",
        "- [AI and machine intelligence](#ai-and-machine-intelligence)",
        "- [By project](#by-project)",
        "- [Legal notices (indexed separately)](#legal-notices-indexed-separately)",
        "",
        "## Who and what we credit, work by work",
        "",
    ]
    by_object: dict[str, list[dict[str, Any]]] = defaultdict(list)
    by_subject: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for e in edges:
        by_object[e["object"]].append(e)
        by_subject[e["subject"]].append(e)
    for obj in sorted(by_object, key=lambda o: name(records, o).lower()):
        aff = records.get(obj, {}).get("affects") or []
        used = ["every Outer Void repository"] if "*" in aff else sorted(
            {name(records, r) for r in aff if str(r).startswith("repo:")})
        out.append(f"### {name(records, obj)}")
        out.append("")
        if used:
            out.append(f"Used by: {', '.join(used)}.")
            out.append("")
        for e in sorted(by_object[obj], key=lambda e: (e["role"], name(records, e["subject"]).lower())):
            links = ", ".join(source_link(s) for s in e.get("sources") or [])
            status = "" if e.get("status", "current") == "current" else f" ({e['status']})"
            qual = "" if e.get("verification") == "VERIFIED" else f" [{e.get('verification')}]"
            out.append(f"- **{name(records, e['subject'])}**: {e['statement']}{status}{qual} ({links})")
        out.append("")
    out += ["## People", ""]
    people = sorted((r for r in records if r.startswith("person:")), key=lambda r: name(records, r).lower())
    for pid in people:
        rec = records[pid]
        credited = [e["statement"] for e in by_subject.get(pid, [])]
        legacy = [name(records, a) for a in rec.get("affects") or []]
        what = "; ".join(credited) or (f"Credited in connection with {', '.join(legacy)}." if legacy else "")
        notes = f" {rec['notes']}" if rec.get("notes") and not credited else ""
        out.append(f"- **{rec['name']}**: {what}{notes}")
    out += ["", "## Communities and organizations", ""]
    for cid in sorted((r for r in records if r.startswith(("community:", "org:"))), key=lambda r: name(records, r).lower()):
        rec = records[cid]
        credited = [e["statement"] for e in by_subject.get(cid, [])]
        legacy = sorted({name(records, a) for a in rec.get("affects") or []})
        parts = credited + ([f"Related to {', '.join(legacy)}."] if legacy and not credited else [])
        out.append(f"- **{rec['name']}**: {' '.join(parts) or (rec.get('notes') or '')}".rstrip())
    out += ["", "## AI and machine intelligence", "",
            "AI tools are credited as assistance or as models and runtimes. They are not authors or copyright holders.",
            "Verification says how each use is known: commit evidence (VERIFIED/INFERRED) or the owner's",
            "declaration (OWNER_REPORTED).", ""]
    for aid in sorted((r for r in records if r.startswith(("ai:", "model:"))), key=lambda r: name(records, r).lower()):
        rec = records[aid]
        vendor = f" ({name(records, rec['vendor'])})" if rec.get("vendor") else ""
        uses = ", ".join(sorted({name(records, a) for a in rec.get("affects") or []})) or "not tied to a repository"
        out.append(f"- **{rec['name']}**{vendor}: {uses}. Verification: {rec.get('verification')}.")
    out += ["", "## By project", ""]
    for entry in repo_map:
        rid = entry["repo"]
        out.append(f"### {name(records, rid)} (`{rid}`)")
        out.append("")
        credited = affects.get(rid, []) + [r for r in records if r.startswith("LIN-") and records[r].get("target") == rid]
        if not credited:
            out += ["No third-party credits recorded yet.", ""]
            continue
        for title, test in GROUPS:
            items = sorted({c for c in credited if not c.startswith("LIN-") and test(c, records[c])},
                           key=lambda c: name(records, c).lower())
            if title.startswith("Upstream"):
                items += [f"{c}" for c in credited if c.startswith("LIN-")]
            if items:
                shown = ", ".join(
                    f"{name(records, records[c]['source'])} ({records[c]['kind'].lower().replace('_', ' ')})"
                    if c.startswith("LIN-") else name(records, c) for c in items)
                out.append(f"- **{title}**: {shown}")
        out.append("")
    out += ["## Legal notices (indexed separately)", "",
            "These works carry notices that their licences require. The notices themselves travel with the",
            "repositories that ship the works. This index points to them; it does not replace them.", "",
            "| Work | Licence | Required notice |", "|---|---|---|"]
    for rid in sorted(records, key=lambda r: name(records, r).lower()):
        rec = records[rid]
        if "REQUIRED_LICENSE_NOTICE" in rels(rec):
            lic = rec.get("license") or rec.get("spdx") or ""
            out.append(f"| {name(records, rid)} | {lic} | {str(rec.get('required_notice') or rec.get('license_file') or '').replace('|', '/')} |")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    text = render(ROOT)
    path = ROOT / "ACKNOWLEDGMENTS.md"
    if "--check" in sys.argv:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            print("ACKNOWLEDGMENTS.md is stale; run tools/render_acknowledgments.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
