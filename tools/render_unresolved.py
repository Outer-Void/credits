#!/usr/bin/env python3
"""Render reports/unresolved-provenance.md from provenance/unresolved.yaml and every record that links to it."""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    unresolved = yaml.safe_load((ROOT / "provenance" / "unresolved.yaml").read_text())["unresolved"]
    linked: dict[str, list[str]] = {u["id"]: [] for u in unresolved}
    for path in (sorted((ROOT / "catalog").glob("*.yaml")) + sorted((ROOT / "projects").glob("*.yaml"))
                 + [ROOT / "provenance" / "attribution-graph.yaml"]):
        doc = yaml.safe_load(path.read_text())
        items = [doc["project"]] if "project" in doc else next(v for k, v in doc.items() if k != "schema_version") or []
        for rec in items:
            refs = rec.get("unresolved")
            for u in [refs] if isinstance(refs, str) else (refs or []):
                linked.setdefault(u, []).append(rec["id"])
    lines = [
        "# Unresolved provenance",
        "",
        "Generated by `tools/render_unresolved.py` from `provenance/unresolved.yaml`. Do not edit by hand.",
        "Unknown provenance is listed here instead of guessed. Each item names its owner and the records it blocks.",
        "",
        "| ID | Status | Title | Owner | Linked records |",
        "|---|---|---|---|---|",
    ]
    for u in unresolved:
        recs = linked.get(u["id"], [])
        shown = ", ".join(f"`{r}`" for r in recs[:6]) + (f" (+{len(recs) - 6} more)" if len(recs) > 6 else "")
        lines.append(f"| {u['id']} | {u.get('status', 'open')} | {u['title']} | {u['owner']} | {shown or '-'} |")
    lines += ["", "## Details", ""]
    for u in unresolved:
        lines += [f"### {u['id']}: {u['title']}", "", u["detail"], ""]
        if u.get("resolution"):
            lines += [f"**Resolved:** {u['resolution']}", ""]
    out = ROOT / "reports" / "unresolved-provenance.md"
    text = "\n".join(lines).rstrip() + "\n"
    if "--check" in sys.argv:
        if out.read_text() != text:
            print("reports/unresolved-provenance.md is stale; run tools/render_unresolved.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
